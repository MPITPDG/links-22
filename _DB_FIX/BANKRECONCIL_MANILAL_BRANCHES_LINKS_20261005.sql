/* NEFT / RTGS : '|' at position 5, reference after the pipe up to the first space (IMPS handled separately below) */
SELECT	PK_ID,ltrim(rtrim(DATE)),
		Btransaction AS OriginalData,
		LEFT(Btransaction, CHARINDEX('|', Btransaction) - 1) AS BeforePipe,
		SUBSTRING(Btransaction, CHARINDEX('|', Btransaction) + 1, CHARINDEX(' ', Btransaction, CHARINDEX('|', Btransaction)) - CHARINDEX('|', Btransaction) - 1) AS BeforeFirstSpace
		,deposit,WITHDRAWAL,CASE WHEN DEPOSIT <> 0.00 THEN 'BR' ELSE 'BP' END,''
FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT
WHERE	FK_LOGID=@FK_LOGID
		AND CHARINDEX('|', Btransaction, 5) = 5 AND BTRANSACTION NOT LIKE 'IMPS|%'

UNION ALL

/* BANK TRANSFER : '|' at position 3, reference after the pipe up to the first space */
SELECT	PK_ID,ltrim(rtrim(DATE)),
		Btransaction AS OriginalData,
		LEFT(Btransaction, CHARINDEX('|', Btransaction) - 1) AS BeforePipe,
		SUBSTRING(RIGHT(Btransaction, LEN(Btransaction) - CHARINDEX('|', Btransaction)), 1, CHARINDEX(' ', RIGHT(Btransaction, LEN(Btransaction) - CHARINDEX('|', Btransaction))) - 1) AS BeforeFirstSpace
		,deposit,WITHDRAWAL ,CASE WHEN DEPOSIT <> 0.00 THEN 'BR' ELSE 'BP' END,''
FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT
WHERE	FK_LOGID=@FK_LOGID
		AND CHARINDEX('|', Btransaction, 3) =3

UNION ALL

/* INTERNATIONAL TRANSFER : '|' at position 17, reference is the text before the pipe */
SELECT	PK_ID,ltrim(rtrim(DATE)),
		Btransaction AS OriginalData,
		SUBSTRING(Btransaction, 1, 2) AS BeforePipe,
		SUBSTRING(Btransaction, 1, CHARINDEX('|', Btransaction) - 1) AS BeforeFirstSpace
		,deposit,WITHDRAWAL ,CASE WHEN DEPOSIT <> 0.00 THEN 'BR' ELSE 'BP' END,''
FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT
WHERE	FK_LOGID=@FK_LOGID
		AND CHARINDEX('|', Btransaction, 17) =17 AND BTRANSACTION NOT LIKE 'NEFT RETURN%'

UNION ALL

/* NEFT RETURN : '|' at position 12, reference after the pipe up to the first space */
SELECT	PK_ID,ltrim(rtrim(DATE)),
		Btransaction AS OriginalData,
		LEFT(Btransaction, CHARINDEX('|', Btransaction) - 1) AS BeforePipe,
		SUBSTRING(RIGHT(Btransaction, LEN(Btransaction) - CHARINDEX('|', Btransaction)), 1, CHARINDEX(' ', RIGHT(Btransaction, LEN(Btransaction) - CHARINDEX('|', Btransaction))) - 1) AS BeforeFirstSpace
		,deposit,WITHDRAWAL ,CASE WHEN DEPOSIT <> 0.00 THEN 'BR' ELSE 'BP' END,''
FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT
WHERE	FK_LOGID=@FK_LOGID
		AND CHARINDEX('|', Btransaction, 12) =12 AND BTRANSACTION LIKE 'NEFT RETURN%'

UNION ALL

/* ANY OTHER PIPE POSITION : first token (excludes the positions handled above) */
SELECT	PK_ID, ltrim(rtrim(DATE)),
		Btransaction AS OriginalData,
		'' BeforePipe,
		LEFT(Btransaction, CHARINDEX(' ', Btransaction + ' ') - 1) AS BeforeFirstSpace ,deposit,WITHDRAWAL,
		CASE WHEN DEPOSIT <> 0.00 THEN 'BR' ELSE 'BP' END,''
FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT
WHERE   FK_LOGID=@FK_LOGID
		AND CHARINDEX('|', Btransaction, 1) != 3
		AND CHARINDEX('|', Btransaction, 1) != 5
		AND CHARINDEX('|', Btransaction, 1) != 17
		AND CHARINDEX('|', Btransaction, 1) > 0
		AND NOT (CHARINDEX('|', Btransaction, 12) = 12 AND BTRANSACTION LIKE 'NEFT RETURN%')

UNION ALL

/* INTERNATIONAL TRANSFER (IT prefix) : space at position 17, reference = first token */
SELECT	PK_ID,ltrim(rtrim(DATE)),
		Btransaction AS OriginalData,
		SUBSTRING(Btransaction, 1, 2) AS BeforePipe,
		SUBSTRING(Btransaction, 1, CHARINDEX(' ', Btransaction) - 1) AS BeforeFirstSpace
		,deposit,WITHDRAWAL ,CASE WHEN DEPOSIT <> 0.00 THEN 'BR' ELSE 'BP' END,''
FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT
WHERE	FK_LOGID=@FK_LOGID
		AND CHARINDEX(' ', Btransaction, 17) =17 AND SUBSTRING(Btransaction, 1, 2)='IT' AND BTRANSACTION NOT LIKE 'NEFT RETURN%'

UNION ALL

/* NO PIPE AT ALL (and not UPI) : first token. The new IDFC .xls rows land here; their UTR is applied further below. */
SELECT  PK_ID, ltrim(rtrim(DATE)),
		Btransaction AS OriginalData,
		'' BeforePipe,
		LEFT(Btransaction, CHARINDEX(' ', Btransaction + ' ') - 1) AS BeforeFirstSpace,deposit,WITHDRAWAL,
		CASE WHEN DEPOSIT <> 0.00 THEN 'BR' ELSE 'BP' END,''
FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT
WHERE	FK_LOGID=@FK_LOGID
		AND CHARINDEX('|', Btransaction) = 0 AND BTRANSACTION NOT LIKE 'UPI%'

UNION ALL

/* IMPS : 12 characters after "IMPS|" */
SELECT	PK_ID,ltrim(rtrim(DATE)),
		BTRANSACTION AS OriginalData,
		SUBSTRING(BTRANSACTION, 1, CHARINDEX('|', BTRANSACTION) - 1) AS BeforePipe,
		SUBSTRING(BTRANSACTION, CHARINDEX('|', BTRANSACTION) + 1, 12)  AS BeforeFirstSpace,
		deposit,
		WITHDRAWAL,
		CASE WHEN DEPOSIT <> 0.00 THEN 'BR' ELSE 'BP' END,
		''
FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT
WHERE	FK_LOGID=@FK_LOGID AND BTRANSACTION LIKE 'IMPS|%'

UNION ALL

/* UPI : the number between the 1st and 2nd '/' */
SELECT  PK_ID,ltrim(rtrim(DATE)),
		BTRANSACTION AS OriginalData,
		SUBSTRING( BTRANSACTION, 1,CHARINDEX('/', BTRANSACTION) - 1) AS BeforePipe,
		SUBSTRING( BTRANSACTION,
				   CHARINDEX('/', BTRANSACTION) + 1,
				   CHARINDEX('/', BTRANSACTION, CHARINDEX('/', BTRANSACTION) + 2) - CHARINDEX('/', BTRANSACTION) - 1
				 ) AS BeforeFirstSpace,
		deposit,WITHDRAWAL,
		CASE WHEN DEPOSIT <> 0.00 THEN 'BR' ELSE 'BP' END,
		''
FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT
WHERE   FK_LOGID=@FK_LOGID AND BTRANSACTION LIKE 'UPI%'

UNION ALL

/* CASH WITHDRAWAL : reference = last 6 characters */
