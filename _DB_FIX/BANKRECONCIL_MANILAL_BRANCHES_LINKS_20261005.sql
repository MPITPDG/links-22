/* FALLBACK: LEDGER ENTRIES WITH BLANK BANKREFNO ('.' or empty) - match statement row on AMOUNT + DIRECTION + DATE WINDOW (+/-7 DAYS).
   Linked only when the pair is UNIQUE both ways (one statement row <-> one ledger entry); ambiguous ones are left for manual reconciliation. */
