		Btransaction AS OriginalData,
		SUBSTRING(Btransaction, 1, 4) AS BeforePipe,
		SUBSTRING(Btransaction, LEN(Btransaction)-5, 6) AS BeforeFirstSpace
		,deposit,WITHDRAWAL ,CASE WHEN DEPOSIT <> 0.00 THEN 'BR' ELSE 'BP' END,''
FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT
WHERE	FK_LOGID=@FK_LOGID
		AND SUBSTRING(Btransaction, 1, 4)='CASH' AND BTRANSACTION LIKE 'CASH WITHDRAWAL%'

