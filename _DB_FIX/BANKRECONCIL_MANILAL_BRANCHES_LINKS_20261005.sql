SELECT DISTINCT S.PK_ID SID, L.ENTRYNO, L.ENTRYDT, L.STATUS, L.BANKREFNO LBANKREFNO, S.STMTDT
INTO	#FBPAIRS
FROM	( SELECT PK_ID, DEPOSIT, WITHDRAWAL,
				 CONVERT(DATETIME, LTRIM(RTRIM([DATE])), 103) STMTDT
		  FROM	 ACC_BANKRECONCIL_UPLOADSTATEMENT
		  WHERE	 FK_LOGID=@FK_LOGID AND ENTRYNO IS NULL AND LEN(LTRIM(RTRIM([DATE])))=10
		) S
		INNER JOIN ( SELECT ENTRYNO, ENTRYDT, STATUS, BANKREFNO, ACTUALAMOUNT,
							CONVERT(DATETIME, LTRIM(RTRIM(ENTRYDT)), 103) LDT
					 FROM	ACC_BANK
					 WHERE	OURBANK=@OURBANK AND CLEARANCEDATE IS NULL
							AND ISNULL(LTRIM(RTRIM(BANKREFNO)),'') IN ('','.')
							AND LEN(LTRIM(RTRIM(ENTRYDT)))=10
							AND DBO.CONVERTDATE_YYYYMMDD(ENTRYDT) >= @FYSTDT
				   ) L
			ON  ( (L.STATUS='BR' AND S.DEPOSIT>0    AND L.ACTUALAMOUNT=S.DEPOSIT)
			   OR (L.STATUS='BP' AND S.WITHDRAWAL>0 AND L.ACTUALAMOUNT=S.WITHDRAWAL) )
			AND ABS(DATEDIFF(DAY, S.STMTDT, L.LDT)) <= 7

DELETE FROM #FBPAIRS
WHERE	SID IN (SELECT SID FROM #FBPAIRS GROUP BY SID HAVING COUNT(*)>1)
		OR ENTRYNO IN (SELECT ENTRYNO FROM #FBPAIRS GROUP BY ENTRYNO HAVING COUNT(*)>1)

