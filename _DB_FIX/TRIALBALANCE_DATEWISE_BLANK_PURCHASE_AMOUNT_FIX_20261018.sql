--
-- Symptom: the request in TBL_REPORT_LOG (form 189) ends with STATUS 'E' and the report never downloads.
-- Cause: USP_ACCT_RPT_TRIALBALANCE_DATEWISE_LOG and USP_ACCT_RPT_TRIALBALANCE_DATEWISE_ALL_LOG convert
--        ACC_PURCHASEDTLS.PUR_AMOUNT / PUR_DEDUCTION (varchar) with CONVERT(NUMERIC(18,2), ...). A blank value (a single space)
--        raises "Error converting data type varchar to numeric" (error 8114) and the run stops at "READING FROM PURCHASE DETAILS".
--        Two purchase detail rows have a blank value today and both are in the financial year 2026-27:
--          301102606269023 (26/06/2026, PUR_DEDUCTION = ' ')     301102609119012 (11/09/2026, PUR_AMOUNT = ' ')
--        so every run that covers those dates fails; runs for earlier years still work.
-- Fix: a blank value is read as 0:  ISNULL(CONVERT(NUMERIC(18,2), NULLIF(LTRIM(RTRIM(value)), '')), 0)
--      Only those two expressions change in each procedure. Roll back with ROLLBACK_TRIALBALANCE_DATEWISE_BLANK_PURCHASE_AMOUNT_FIX_20261018.sql.
-- Other trial balance procedures that use the same conversion (not changed here): usp_Acct_RPT_Trialbalance_ALL, USP_ACCT_RPT_TRIALBALANCE_DATEWISE,
--      USP_ACCT_RPT_TRIALBALANCE_DATEWISE_ALL, usp_Acct_Rpt_Trialbalance, usp_Acct_Rpt_Trialbalance_byGrp, USP_ACCT_RPT_TRIALBALANCE_PROVISION and others.
