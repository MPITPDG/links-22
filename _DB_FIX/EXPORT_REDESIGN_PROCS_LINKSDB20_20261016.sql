			@ENTRYTIME VARCHAR(15),
			@etaold varchar(10)
	SELECT
			@FLIGHTNO=ISNULL(FLIGHTNO,''),
			@FLIGHTDT = FLIGHTDT,
			@AEROBILLNO=AEROBILLNO,
			@_ACTUALFLIGHTNO=ISNULL(ACTUALFLIGHTNO,''),
			@_ACTUALFLIGHTDT = ACTUALFLIGHTDT,
