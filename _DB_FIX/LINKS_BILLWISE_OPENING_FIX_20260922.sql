DECLARE @OPBASETAB SYSNAME, @OPT SYSNAME, @OPCOLS NVARCHAR(MAX), @OPCHK NVARCHAR(MAX), @OPN INT
SET @OPBASETAB = NULL
DECLARE opt CURSOR LOCAL FAST_FORWARD FOR
    SELECT t.name FROM sys.tables t
     WHERE t.name LIKE 'TBL[_]MASTER[_]%[_]ALLGL' AND ISNUMERIC(SUBSTRING(t.name, 12, 8)) = 1
     ORDER BY SUBSTRING(t.name, 16, 4)
OPEN opt
FETCH NEXT FROM opt INTO @OPT
WHILE @@FETCH_STATUS = 0 AND @OPBASETAB IS NULL
BEGIN
    SET @OPCOLS = ''
    SELECT @OPCOLS = @OPCOLS + N' + ISNULL([' + c.name + N'], 0)'
      FROM sys.columns c
     WHERE c.object_id = OBJECT_ID(N'dbo.' + QUOTENAME(@OPT)) AND c.name LIKE @COMPANYCODE + '%OP'
    IF @OPCOLS <> ''
    BEGIN
        SET @OPN = 0
        SET @OPCHK = N'SELECT @n = COUNT(*) FROM dbo.' + QUOTENAME(@OPT)
                   + N' WHERE LTRIM(RTRIM(CODE)) LIKE ''E%'' AND (0' + @OPCOLS + N') <> 0'
        EXEC sp_executesql @OPCHK, N'@n INT OUTPUT', @n = @OPN OUTPUT
        IF @OPN > 0 SET @OPBASETAB = @OPT
    END
    FETCH NEXT FROM opt INTO @OPT
END
CLOSE opt
DEALLOCATE opt
SET @OPBASETAB = ISNULL(@OPBASETAB, 'TBL_MASTER_010420063103007_ALLGL')
