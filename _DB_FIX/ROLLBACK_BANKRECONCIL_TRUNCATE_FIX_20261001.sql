 /* UPDATING CLEARANCE DATE TO ACC_BANK FROM UPLOADSTATEMENT MATCHING AMOUNT AND BANKREFNO*/

 UPDATE A SET A.CLEARANCEDATE=CONVERT(DATETIME,B.CLEARANCEDT,103) 
 FROM	ACC_BANK A INNER JOIN 
		( SELECT BANKREFNO,CLEARANCEDT ,DEPOSIT  FROM #TMPBANKRECONCILSTMT 
		  WHERE TRANSTYPE='BR' 
		) B ON A.BANKREFNO=B.BANKREFNO AND A.ACTUALAMOUNT=B.DEPOSIT
 WHERE  DBO.CONVERTDATE_YYYYMMDD(A.ENTRYDT) >= @FYSTDT  --'20230401'
		--BETWEEN DBO.CONVERTDATE_YYYYMMDD(@FROMDT) and DBO.CONVERTDATE_YYYYMMDD(@TODT)
		AND A.OURBANK=@OURBANK
 --AND TRY_CAST(CLEARANCEDT AS DATETIME) IS NULL


 UPDATE	A SET A.CLEARANCEDATE=CONVERT(DATETIME,B.CLEARANCEDT,103) 
 FROM	ACC_BANK A INNER JOIN 
		( SELECT BANKREFNO,CLEARANCEDT CLEARANCEDT,WITHDRAWAL
		  FROM #TMPBANKRECONCILSTMT 
		  WHERE TRANSTYPE='BP' 
		) B ON A.BANKREFNO=B.BANKREFNO AND A.ACTUALAMOUNT=B.WITHDRAWAL
WHERE	DBO.CONVERTDATE_YYYYMMDD(A.ENTRYDT) >= @FYSTDT --DBO.CONVERTDATE_YYYYMMDD(@FROMDT) --BETWEEN DBO.CONVERTDATE_YYYYMMDD(@FROMDT) and DBO.CONVERTDATE_YYYYMMDD(@TODT)
		AND A.OURBANK=@OURBANK
 --AND TRY_CAST(CLEARANCEDT AS DATETIME) IS NULL

 /* UPDATING ENTRYNO,ENTRYDT,ENTRYTYPE,BANKRENO FOR ACC_BANK TO UPLOADSTATEMENTTABLE  */

 UPDATE A SET A.ENTRYNO=B.ENTRYNO,A.ENTRYDT=B.ENTRYDT,A.ENTRYTYPE=B.STATUS,A.USERBANKREFNO=B.BANKREFNO
 FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT A INNER JOIN 
		( SELECT BANKREFNO,ENTRYNO,ENTRYDT,STATUS,ACTUALAMOUNT,OURBANK
		  FROM	 ACC_BANK 
		  WHERE  STATUS='BR' 
				 AND DBO.CONVERTDATE_YYYYMMDD(ENTRYDT) >= @FYSTDT    --BETWEEN DBO.CONVERTDATE_YYYYMMDD(@FROMDT) and DBO.CONVERTDATE_YYYYMMDD(@TODT)
		) B ON A.BANKREFNO=B.BANKREFNO AND A.DEPOSIT=B.ACTUALAMOUNT  --ON A.WITHDRAWAL=B.ACTUALAMOUNT  
  WHERE  B.OURBANK=@OURBANK  AND FK_LOGID=@FK_LOGID 

 UPDATE A SET A.ENTRYNO=B.ENTRYNO, A.ENTRYDT=B.ENTRYDT, A.ENTRYTYPE=B.STATUS, A.USERBANKREFNO=B.BANKREFNO
 FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT A INNER JOIN 
		( SELECT BANKREFNO,ENTRYNO,ENTRYDT,STATUS,ACTUALAMOUNT,OURBANK
		  FROM	 ACC_BANK 
		  WHERE	 STATUS='BP'  
				 AND DBO.CONVERTDATE_YYYYMMDD(ENTRYDT) >= @FYSTDT --BETWEEN DBO.CONVERTDATE_YYYYMMDD(@FROMDT) and DBO.CONVERTDATE_YYYYMMDD(@TODT) 
				 AND OURBANK=@OURBANK
		) B ON A.BANKREFNO=B.BANKREFNO AND A.WITHDRAWAL=B.ACTUALAMOUNT  --ON A.WITHDRAWAL=B.ACTUALAMOUNT
 WHERE   B.OURBANK=@OURBANK AND FK_LOGID=@FK_LOGID 


  UPDATE A SET A.USERBANKREFNO=B.BANKREFNO,A.LCLEARNCEDT=CONVERT(VARCHAR,B.CLEARANCEDATE,103)
  FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT A INNER JOIN 
		( SELECT BANKREFNO,clearanceDate,ENTRYNO 
		  FROM   ACC_BANK 
		  WHERE  DBO.CONVERTDATE_YYYYMMDD(ENTRYDT) >= @FYSTDT 	 -- BETWEEN DBO.CONVERTDATE_YYYYMMDD(@FROMDT) and DBO.CONVERTDATE_YYYYMMDD(@TODT)
				 AND OURBANK=@OURBANK 
	  ) B ON A.ENTRYNO=B.ENTRYNO 
  WHERE A.ENTRYNO=B.ENTRYNO
	 

 UPDATE A SET A.LAMOUNT=B.AMOUNT
 FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT A INNER JOIN 
		(	SELECT	SUM(CONVERT(FLOAT,AMOUNT)) AMOUNT, ACC_BANKDTLS.ENTRYNO 
			FROM	ACC_BANKDTLS INNER JOIN ACC_BANK ON ACC_BANK.ENTRYNO=ACC_BANKDTLS.ENTRYNO 
			WHERE	DBO.CONVERTDATE_YYYYMMDD(ENTRYDT) >= @FYSTDT  --BETWEEN DBO.CONVERTDATE_YYYYMMDD(@FROMDT) and DBO.CONVERTDATE_YYYYMMDD(@TODT)
					AND OURBANK=@OURBANK 
			GROUP BY ACC_BANKDTLS.ENTRYNO
		) B ON A.ENTRYNO=B.ENTRYNO


 UPDATE A SET A.LDEDUCTION=B.DEDUCTION
 FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT A INNER JOIN 
		( SELECT SUM(CONVERT(FLOAT,DEDUCTION)) DEDUCTION,
				 ACC_BANKDTLS.ENTRYNO 
		  FROM	 ACC_BANKDTLS INNER JOIN ACC_BANK ON ACC_BANK.ENTRYNO=ACC_BANKDTLS.ENTRYNO 
		  WHERE	 DBO.CONVERTDATE_YYYYMMDD(ENTRYDT) >= @FYSTDT 			 --BETWEEN DBO.CONVERTDATE_YYYYMMDD(@FROMDT) and DBO.CONVERTDATE_YYYYMMDD(@TODT)
				 AND OURBANK=@OURBANK 
		  GROUP BY ACC_BANKDTLS.ENTRYNO
		) B	 ON A.ENTRYNO=B.ENTRYNO


IF EXISTS(SELECT BANKREFNO  FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT 
