		ENTRYDT,
		ENTRYTYPE,
		LAMOUNT AMOUNT, 
		LDEDUCTION DEDUCTION,
		LCLEARNCEDT CLEARANCEDT
FROM	ACC_BANKRECONCIL_UPLOADSTATEMENT 
WHERE	FK_LOGID=@FK_LOGID 
		AND ENTRYNO  IS NULL 
UNION ALL 
SELECT	BANKREFNO='', 
		DEPOSIT=0,
		WITHDRAWAL=0,
		CLEARANCEDT='' ,
		'  ' , 
		USERBANKREFNO=BANKREFNO ,
		ENTRYNO,
		ENTRYDT,
		ENTRYTYPE=[STATUS], 
		AMOUNT=ACTUALAMOUNT, 
		DEDUCTION=0, 
		CLEARANCEDT=CLEARANCEDATE
FROM	ACC_BANk 
WHERE	CLEARANCEDATE IS NULL 
		AND DBO.CONVERTDATE_YYYYMMDD(ENTRYDT) BETWEEN DBO.CONVERTDATE_YYYYMMDD(@FROMDT) and DBO.CONVERTDATE_YYYYMMDD(@TODT) 
		AND  OURBANK=@OURBANK


