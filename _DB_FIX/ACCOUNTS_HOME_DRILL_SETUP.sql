    CREATE TABLE #OJ (INV_NO VARCHAR(15), JOBNO VARCHAR(25))
    INSERT INTO #OJ (INV_NO, JOBNO)
    SELECT DISTINCT o.INV_NO, LTRIM(RTRIM(jn.inv_jobno))
      FROM #OB o
     INNER JOIN acc_invjobno jn ON LTRIM(RTRIM(jn.inv_no)) = o.INV_NO
     WHERE ISNULL(jn.inv_jobno, '') <> ''

    CREATE TABLE #OJOB (JOBNO VARCHAR(25) PRIMARY KEY)
    INSERT INTO #OJOB (JOBNO) SELECT DISTINCT JOBNO FROM #OJ

    CREATE TABLE #OJINV (JOBNO VARCHAR(25), INV_NO VARCHAR(15))
    INSERT INTO #OJINV (JOBNO, INV_NO)
    SELECT DISTINCT j.JOBNO, LTRIM(RTRIM(jn.inv_no))
      FROM #OJOB j
     INNER JOIN acc_invjobno jn ON LTRIM(RTRIM(jn.inv_jobno)) = j.JOBNO
     INNER JOIN acc_invoice iv  ON LTRIM(RTRIM(iv.inv_no)) = LTRIM(RTRIM(jn.inv_no))
