             INNER JOIN acc_bank b ON b.entryno = d.entryno
             WHERE ISNULL(d.jobno, '') <> ''
               AND d.entrytype = 'JB'
               AND LTRIM(RTRIM(d.client)) IN (SELECT ACCTCODE FROM #JOBHEAD)
               AND b.status IN ('BP', 'CP', 'CE')
            UNION ALL
            SELECT LTRIM(RTRIM(jd.jv_jobno)),
