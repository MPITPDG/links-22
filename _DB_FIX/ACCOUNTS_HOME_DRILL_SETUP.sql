    /*=========================================================================
      MARGIN detail - jobs opened this month, exactly the rows behind GOP
    =========================================================================*/
    CREATE TABLE #MJ
    (
        JOBNO       VARCHAR(25) PRIMARY KEY,
        MODE_       VARCHAR(10),
        JOB_DT      DATETIME,
        IS_BILLED   BIT,
        REVENUE     FLOAT,
        COST        FLOAT,
        PARTY       VARCHAR(10),    -- the party on the job file (shipper / importer / misc client)
        BILLED      VARCHAR(10),    -- the party carrying most of the invoice value on the job
        LAST_INV_DT DATETIME
    )

    INSERT INTO #MJ (JOBNO, MODE_, JOB_DT, IS_BILLED, REVENUE, COST)
    SELECT p.JOBNO, MAX(p.MODE_), MAX(j.JOB_DT), MAX(CONVERT(INT, p.IS_BILLED)), SUM(p.REVENUE), SUM(p.COST)
      FROM #PL p
     INNER JOIN #JOBS j ON j.JOBNO = p.JOBNO
     WHERE p.PERIOD = 'M'
     GROUP BY p.JOBNO

    UPDATE M SET PARTY = LTRIM(RTRIM(ISNULL(NULLIF(LTRIM(RTRIM(ISNULL(e.expt_billto, ''))), ''), e.expt_exporter)))
      FROM #MJ M INNER JOIN EXPT_MASTER e ON LTRIM(RTRIM(e.exptno)) = M.JOBNO
    UPDATE M SET PARTY = LTRIM(RTRIM(ISNULL(NULLIF(LTRIM(RTRIM(ISNULL(i.fk_BillTo, ''))), ''), i.fk_Imp_Code)))
      FROM #MJ M INNER JOIN TBL_IMP_IMPORT i ON LTRIM(RTRIM(i.Import_Code)) = M.JOBNO
     WHERE M.PARTY IS NULL
    UPDATE M SET PARTY = LTRIM(RTRIM(m2.CLIENT_CODE))
      FROM #MJ M INNER JOIN EXPT_MASTER_MISC m2 ON LTRIM(RTRIM(m2.JOBNO)) = M.JOBNO
     WHERE M.PARTY IS NULL

    UPDATE M SET BILLED = R.CLIENTCODE
      FROM #MJ M
     INNER JOIN (
                 SELECT X.JOBNO, X.CLIENTCODE,
                        ROW_NUMBER() OVER (PARTITION BY X.JOBNO ORDER BY X.AMT DESC, X.CLIENTCODE) AS RN
                   FROM (SELECT ji.JOBNO, v.CLIENTCODE, SUM(v.TOTALAMT) AS AMT
                           FROM #JOBINV ji INNER JOIN #INV v ON v.INV_NO = ji.INV_NO
                          GROUP BY ji.JOBNO, v.CLIENTCODE) X
                ) R ON R.JOBNO = M.JOBNO AND R.RN = 1

    UPDATE M SET LAST_INV_DT = L.DT
      FROM #MJ M
     INNER JOIN (SELECT ji.JOBNO, MAX(v.INV_DT) AS DT
                   FROM #JOBINV ji INNER JOIN #INV v ON v.INV_NO = ji.INV_NO
                  GROUP BY ji.JOBNO) L ON L.JOBNO = M.JOBNO

    -- Table : summary (REVENUE / COST / GOP equal the home card)
    SELECT '100'                                                   AS STATUS,
           'MARGIN'                                                AS KIND,
           CONVERT(VARCHAR(10), @M_FROM, 103)                      AS FROMDATE,
           CONVERT(VARCHAR(10), @ASON, 103)                        AS ASON,
           @BRANCH_LABEL                                           AS BRANCH,
           COUNT(*)                                                AS JOBS,
           CONVERT(DECIMAL(18,2), ISNULL(SUM(REVENUE), 0))         AS REVENUE,
           CONVERT(DECIMAL(18,2), ISNULL(SUM(COST), 0))            AS COST,
           CONVERT(DECIMAL(18,2), ISNULL(SUM(REVENUE) - SUM(COST), 0)) AS GOP,
           CONVERT(DECIMAL(18,2), CASE WHEN SUM(REVENUE) > 0
                THEN (SUM(REVENUE) - SUM(COST)) / SUM(REVENUE) * 100.0 END) AS MARGIN_PCT,
           SUM(CASE WHEN IS_BILLED = 1 THEN 1 ELSE 0 END)          AS BILLED_JOBS,
           SUM(CASE WHEN IS_BILLED = 0 THEN 1 ELSE 0 END)          AS UNBILLED_JOBS,
           CONVERT(DECIMAL(18,2), ISNULL(SUM(CASE WHEN IS_BILLED = 0 THEN COST ELSE 0 END), 0)) AS UNBILLED_COST,
           SUM(CASE WHEN IS_BILLED = 1 AND REVENUE - COST < 0 THEN 1 ELSE 0 END) AS LOSS_JOBS,
           CONVERT(DECIMAL(18,2), ISNULL(SUM(CASE WHEN IS_BILLED = 1 AND REVENUE - COST < 0 THEN REVENUE - COST ELSE 0 END), 0)) AS LOSS_VALUE,
           -- billed but no cost booked yet: their margin reads ~100% until purchase bills
           -- arrive, which is what lifts a month-to-date margin early in the month
           SUM(CASE WHEN IS_BILLED = 1 AND COST < 0.01 THEN 1 ELSE 0 END) AS NOCOST_JOBS,
           CONVERT(DECIMAL(18,2), ISNULL(SUM(CASE WHEN IS_BILLED = 1 AND COST < 0.01 THEN REVENUE ELSE 0 END), 0)) AS NOCOST_REVENUE
      FROM #MJ

    -- Table1 : by mode
    SELECT MODE_,
           COUNT(*)                                                AS JOBS,
           CONVERT(DECIMAL(18,2), SUM(REVENUE))                    AS REVENUE,
           CONVERT(DECIMAL(18,2), SUM(COST))                       AS COST,
           CONVERT(DECIMAL(18,2), SUM(REVENUE) - SUM(COST))        AS GOP,
           CONVERT(DECIMAL(18,2), CASE WHEN SUM(REVENUE) > 0
                THEN (SUM(REVENUE) - SUM(COST)) / SUM(REVENUE) * 100.0 END) AS MARGIN_PCT
      FROM #MJ
     GROUP BY MODE_
     ORDER BY SUM(REVENUE) - SUM(COST) DESC

    -------------------------------------------------------------------------
    -- CLIENT-WISE SPLIT of each job - the same rule as the Finance Dashboard.
    -- Income goes to the client each invoice was raised on; each cost line follows
    -- the client billed for the matching charge (TBL_MST_JOB_COST_PAIRING, or the
    -- head itself), split by what each was billed; cost with no matching charge is
    -- shared by income (UNMATCHED); a job with nothing billed keeps its cost on its
    -- party. Job totals, and so the GOP card, do not change.
    -------------------------------------------------------------------------
    CREATE TABLE #MJIC (JOBNO VARCHAR(25), CLIENTCODE VARCHAR(10), HEAD VARCHAR(10), AMT FLOAT)
    INSERT INTO #MJIC (JOBNO, CLIENTCODE, HEAD, AMT)
    SELECT Z.JOBNO, Z.CLIENTCODE, Z.HEAD, SUM(Z.AMT)
      FROM (
            SELECT ji.JOBNO, v.CLIENTCODE, LTRIM(RTRIM(ISNULL(ic.inv_account, ''))) AS HEAD,
                   CONVERT(FLOAT, ISNULL(NULLIF(LTRIM(RTRIM(ic.inv_inramt)), ''), '0'))
                       / CONVERT(FLOAT, CASE WHEN ISNULL(n.NJOBS, 0) < 1 THEN 1 ELSE n.NJOBS END) AS AMT
              FROM #JOBINV ji
             INNER JOIN #MJ mj ON mj.JOBNO = ji.JOBNO
             INNER JOIN #INV v ON v.INV_NO = ji.INV_NO
             INNER JOIN acc_invcharge ic ON ic.inv_no = ji.INV_NO
              LEFT JOIN #INVJOBCNT n ON n.INV_NO = ji.INV_NO
              LEFT JOIN dbo.TBL_MST_FIN_SERVICE_CATEGORY sc ON sc.ACCTCODE = LTRIM(RTRIM(ISNULL(ic.inv_account, '')))
             WHERE ISNULL(sc.CATEGORY, 'OTHER') NOT IN ('TAX', 'EXCL')
            UNION ALL
            SELECT ji.JOBNO, v.CLIENTCODE, LTRIM(RTRIM(ISNULL(ic.inv_account, ''))),
                   CONVERT(FLOAT, ISNULL(NULLIF(LTRIM(RTRIM(ic.inv_inramt)), ''), '0'))
                       / CONVERT(FLOAT, CASE WHEN ISNULL(n.NJOBS, 0) < 1 THEN 1 ELSE n.NJOBS END)
              FROM #JOBINV ji
             INNER JOIN #MJ mj ON mj.JOBNO = ji.JOBNO
             INNER JOIN #INV v ON v.INV_NO = ji.INV_NO
             INNER JOIN acc_invcharge1 ic ON ic.inv_no = ji.INV_NO
              LEFT JOIN #INVJOBCNT n ON n.INV_NO = ji.INV_NO
              LEFT JOIN dbo.TBL_MST_FIN_SERVICE_CATEGORY sc ON sc.ACCTCODE = LTRIM(RTRIM(ISNULL(ic.inv_account, '')))
             WHERE ISNULL(sc.CATEGORY, 'OTHER') NOT IN ('TAX', 'EXCL')
           ) Z
     GROUP BY Z.JOBNO, Z.CLIENTCODE, Z.HEAD
    CREATE CLUSTERED INDEX IX_MJIC ON #MJIC (JOBNO, HEAD)

    -- cost per job and head: the same lines as the GOP card's cost
    CREATE TABLE #MJEC (JOBNO VARCHAR(25), HEAD VARCHAR(10), AMT FLOAT)
    INSERT INTO #MJEC (JOBNO, HEAD, AMT)
    SELECT X.JOBNO, X.HEAD, SUM(X.AMT)
      FROM (
            SELECT LTRIM(RTRIM(pd.pur_jobno)) AS JOBNO, LTRIM(RTRIM(pd.pur_account)) AS HEAD,
                   CONVERT(FLOAT, ISNULL(NULLIF(LTRIM(RTRIM(pd.pur_amount)), ''), '0')) AS AMT
              FROM acc_purchasedtls pd
             WHERE ISNULL(pd.pur_jobno, '') <> ''
               AND LTRIM(RTRIM(pd.pur_account)) IN (SELECT ACCTCODE FROM #JOBHEAD)
            UNION ALL
            SELECT LTRIM(RTRIM(d.jobno)), LTRIM(RTRIM(d.client)),
                   CONVERT(FLOAT, ISNULL(NULLIF(LTRIM(RTRIM(d.amount)), ''), '0'))
              FROM acc_bankdtls d
             INNER JOIN acc_bank b ON b.entryno = d.entryno
             WHERE ISNULL(d.jobno, '') <> ''
               AND d.entrytype = 'JB'
               AND LTRIM(RTRIM(d.client)) IN (SELECT ACCTCODE FROM #JOBHEAD)
               AND b.status IN ('BP', 'CP', 'CE')
            UNION ALL
            SELECT LTRIM(RTRIM(jd.jv_jobno)), LTRIM(RTRIM(jd.jv_account)),
                   CONVERT(FLOAT, ISNULL(NULLIF(LTRIM(RTRIM(jd.jv_debit)), ''), '0'))
              FROM acc_JournalVoucDtls jd
             WHERE ISNULL(jd.jv_jobno, '') <> ''
               AND LTRIM(RTRIM(jd.jv_account)) IN (SELECT ACCTCODE FROM #JOBHEAD)
           ) X
     INNER JOIN #MJ mj ON mj.JOBNO = X.JOBNO
     GROUP BY X.JOBNO, X.HEAD
    CREATE CLUSTERED INDEX IX_MJEC ON #MJEC (JOBNO, HEAD)

    CREATE TABLE #MJCH (JOBNO VARCHAR(25), CLIENTCODE VARCHAR(10), HEAD VARCHAR(10), AMT FLOAT)
    INSERT INTO #MJCH (JOBNO, CLIENTCODE, HEAD, AMT)
    SELECT JOBNO, CLIENTCODE, HEAD, SUM(AMT) FROM #MJIC GROUP BY JOBNO, CLIENTCODE, HEAD HAVING SUM(AMT) > 0.01
    CREATE CLUSTERED INDEX IX_MJCH ON #MJCH (JOBNO, HEAD)

    CREATE TABLE #MJC (JOBNO VARCHAR(25), CLIENTCODE VARCHAR(10), INC FLOAT)
    INSERT INTO #MJC (JOBNO, CLIENTCODE, INC)
    SELECT JOBNO, CLIENTCODE, SUM(AMT) FROM #MJIC GROUP BY JOBNO, CLIENTCODE HAVING SUM(AMT) > 0.01

    -- the pairing table comes with the Finance Dashboard script; until that has run, a
    -- head only pairs with itself
    CREATE TABLE #MPAIRS (COSTHEAD VARCHAR(10), INCHEAD VARCHAR(10))
    IF OBJECT_ID('dbo.TBL_MST_JOB_COST_PAIRING') IS NOT NULL
        EXEC ('INSERT INTO #MPAIRS (COSTHEAD, INCHEAD) SELECT DISTINCT LTRIM(RTRIM(COSTHEAD)), LTRIM(RTRIM(INCHEAD)) FROM dbo.TBL_MST_JOB_COST_PAIRING')
    INSERT INTO #MPAIRS (COSTHEAD, INCHEAD)
    SELECT DISTINCT e.HEAD, e.HEAD FROM #MJEC e
     WHERE NOT EXISTS (SELECT 1 FROM #MPAIRS p WHERE p.COSTHEAD = e.HEAD AND p.INCHEAD = e.HEAD)

    CREATE TABLE #MJECB (JOBNO VARCHAR(25), COSTHEAD VARCHAR(10), CLIENTCODE VARCHAR(10), BILLED FLOAT)
    INSERT INTO #MJECB (JOBNO, COSTHEAD, CLIENTCODE, BILLED)
    SELECT e.JOBNO, e.HEAD, h.CLIENTCODE, SUM(h.AMT)
      FROM #MJEC e
     INNER JOIN #MPAIRS p ON p.COSTHEAD = e.HEAD
     INNER JOIN #MJCH h ON h.JOBNO = e.JOBNO AND h.HEAD = p.INCHEAD
     GROUP BY e.JOBNO, e.HEAD, h.CLIENTCODE

    CREATE TABLE #MALLOC (JOBNO VARCHAR(25), CLIENTCODE VARCHAR(10), COST FLOAT, UNMATCHED FLOAT)
    INSERT INTO #MALLOC (JOBNO, CLIENTCODE, COST, UNMATCHED)
    SELECT e.JOBNO, b.CLIENTCODE, e.AMT * b.BILLED / t.TOT, 0
      FROM #MJEC e
     INNER JOIN #MJECB b ON b.JOBNO = e.JOBNO AND b.COSTHEAD = e.HEAD
     INNER JOIN (SELECT JOBNO, COSTHEAD, SUM(BILLED) AS TOT FROM #MJECB GROUP BY JOBNO, COSTHEAD) t
             ON t.JOBNO = e.JOBNO AND t.COSTHEAD = e.HEAD
    INSERT INTO #MALLOC (JOBNO, CLIENTCODE, COST, UNMATCHED)
    SELECT e.JOBNO, c.CLIENTCODE, e.AMT * c.INC / jt.TOT, e.AMT * c.INC / jt.TOT
      FROM #MJEC e
     INNER JOIN #MJC c ON c.JOBNO = e.JOBNO
     INNER JOIN (SELECT JOBNO, SUM(INC) AS TOT FROM #MJC GROUP BY JOBNO) jt ON jt.JOBNO = e.JOBNO
     WHERE NOT EXISTS (SELECT 1 FROM #MJECB b WHERE b.JOBNO = e.JOBNO AND b.COSTHEAD = e.HEAD)
    INSERT INTO #MALLOC (JOBNO, CLIENTCODE, COST, UNMATCHED)
    SELECT e.JOBNO, ISNULL(M.BILLED, ISNULL(M.PARTY, '')), e.AMT, 0
      FROM #MJEC e
     INNER JOIN #MJ M ON M.JOBNO = e.JOBNO
     WHERE NOT EXISTS (SELECT 1 FROM #MJECB b WHERE b.JOBNO = e.JOBNO AND b.COSTHEAD = e.HEAD)
       AND NOT EXISTS (SELECT 1 FROM #MJC c WHERE c.JOBNO = e.JOBNO)

    CREATE TABLE #MJCP (JOBNO VARCHAR(25), CLIENTCODE VARCHAR(10), REVENUE FLOAT, COST FLOAT, UNMATCHED FLOAT)
    INSERT INTO #MJCP (JOBNO, CLIENTCODE, REVENUE, COST, UNMATCHED)
    SELECT X.JOBNO, X.CLIENTCODE, SUM(X.R), SUM(X.C), SUM(X.U)
      FROM (
            SELECT JOBNO, CLIENTCODE, AMT AS R, 0 AS C, 0 AS U FROM #MJIC
            UNION ALL
            SELECT JOBNO, CLIENTCODE, 0, COST, UNMATCHED FROM #MALLOC
            UNION ALL
            SELECT M.JOBNO, ISNULL(M.BILLED, ISNULL(M.PARTY, '')), 0, 0, 0
              FROM #MJ M
             WHERE NOT EXISTS (SELECT 1 FROM #MJIC i WHERE i.JOBNO = M.JOBNO)
               AND NOT EXISTS (SELECT 1 FROM #MALLOC a WHERE a.JOBNO = M.JOBNO)
           ) X
     GROUP BY X.JOBNO, X.CLIENTCODE

    -- Table2 : by client, from the split (a job billed to two clients counts for both)
    SELECT p.CLIENTCODE,
           MAX(LTRIM(RTRIM(ISNULL(e.exp_name, CASE WHEN p.CLIENTCODE = '' THEN '(not recorded)' ELSE p.CLIENTCODE END)))) AS CLIENTNAME,
           COUNT(*)                                                AS JOBS,
           SUM(CASE WHEN c.N > 1 THEN 1 ELSE 0 END)                AS SHARED_JOBS,
           CONVERT(DECIMAL(18,2), SUM(p.REVENUE))                  AS REVENUE,
           CONVERT(DECIMAL(18,2), SUM(p.COST))                     AS COST,
           CONVERT(DECIMAL(18,2), SUM(p.UNMATCHED))                AS UNMATCHED_COST,
           CONVERT(DECIMAL(18,2), SUM(p.REVENUE) - SUM(p.COST))    AS GOP,
           CONVERT(DECIMAL(18,2), CASE WHEN SUM(p.REVENUE) > 0
                THEN (SUM(p.REVENUE) - SUM(p.COST)) / SUM(p.REVENUE) * 100.0 END) AS MARGIN_PCT
      FROM #MJCP p
     INNER JOIN (SELECT JOBNO, COUNT(*) AS N FROM #MJCP GROUP BY JOBNO) c ON c.JOBNO = p.JOBNO
      LEFT JOIN exp_master e ON LTRIM(RTRIM(e.exp_code)) = p.CLIENTCODE
     GROUP BY p.CLIENTCODE
     ORDER BY SUM(p.REVENUE) - SUM(p.COST) DESC

    -- Table3 : jobs
    SELECT M.JOBNO,
           M.MODE_,
           CONVERT(VARCHAR(10), M.JOB_DT, 103)                     AS JOB_DATE,
           CONVERT(VARCHAR(8),  M.JOB_DT, 112)                     AS JOB_YMD,
           ISNULL(M.BILLED, ISNULL(M.PARTY, ''))                   AS CLIENTCODE,
           LTRIM(RTRIM(ISNULL(eb.exp_name, ISNULL(M.BILLED, ISNULL(M.PARTY, ''))))) AS CLIENTNAME,
           LTRIM(RTRIM(ISNULL(ep.exp_name, ISNULL(M.PARTY, ''))))   AS SHIPPERNAME,
           M.IS_BILLED,
           CONVERT(VARCHAR(10), M.LAST_INV_DT, 103)                AS LAST_BILLED,
           CONVERT(DECIMAL(18,2), M.REVENUE)                       AS INCOME,
           CONVERT(DECIMAL(18,2), M.COST)                          AS EXPENSE,
           CONVERT(DECIMAL(18,2), M.REVENUE - M.COST)              AS GOP,
           CONVERT(DECIMAL(18,2), CASE WHEN M.REVENUE <> 0
                THEN (M.REVENUE - M.COST) / M.REVENUE * 100.0 END) AS MARGIN_PCT
      FROM #MJ M
      LEFT JOIN exp_master eb ON LTRIM(RTRIM(eb.exp_code)) = ISNULL(M.BILLED, M.PARTY)
      LEFT JOIN exp_master ep ON LTRIM(RTRIM(ep.exp_code)) = M.PARTY
     ORDER BY M.REVENUE - M.COST DESC

    -- Table4 : each job's share per client (the rows behind Table2)
    SELECT p.JOBNO,
           p.CLIENTCODE,
           LTRIM(RTRIM(ISNULL(e.exp_name, p.CLIENTCODE)))          AS CLIENTNAME,
           CONVERT(VARCHAR(10), M.JOB_DT, 103)                     AS JOB_DATE,
           M.MODE_,
           CONVERT(DECIMAL(18,2), p.REVENUE)                       AS INCOME,
           CONVERT(DECIMAL(18,2), p.COST)                          AS EXPENSE,
           CONVERT(DECIMAL(18,2), p.UNMATCHED)                     AS UNMATCHED_COST,
           CONVERT(DECIMAL(18,2), p.REVENUE - p.COST)              AS GOP,
           CONVERT(DECIMAL(18,2), CASE WHEN p.REVENUE <> 0
                THEN (p.REVENUE - p.COST) / p.REVENUE * 100.0 END) AS MARGIN_PCT,
           c.N                                                     AS CLIENTS_ON_JOB
      FROM #MJCP p
     INNER JOIN #MJ M ON M.JOBNO = p.JOBNO
     INNER JOIN (SELECT JOBNO, COUNT(*) AS N FROM #MJCP GROUP BY JOBNO) c ON c.JOBNO = p.JOBNO
      LEFT JOIN exp_master e ON LTRIM(RTRIM(e.exp_code)) = p.CLIENTCODE
     ORDER BY p.CLIENTCODE, p.REVENUE - p.COST DESC
    END
END
