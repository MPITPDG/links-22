           ) Z
     GROUP BY Z.JOBNO

    -- Table4 : jobs on each overdue bill
    SELECT oj.INV_NO,
           oj.JOBNO,
           CONVERT(VARCHAR(10), d.JOB_DT, 103)                             AS JOB_DATE,
