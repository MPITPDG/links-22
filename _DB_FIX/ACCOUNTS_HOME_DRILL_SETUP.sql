              FROM EXPT_MASTER e INNER JOIN #OJOB j ON j.JOBNO = LTRIM(RTRIM(e.exptno))
             WHERE LEN(ISNULL(e.expt_docrecd, '')) = 10
            UNION ALL
            SELECT LTRIM(RTRIM(i.Import_Code)), i.Import_Date
              FROM TBL_IMP_IMPORT i INNER JOIN #OJOB j ON j.JOBNO = LTRIM(RTRIM(i.Import_Code))
