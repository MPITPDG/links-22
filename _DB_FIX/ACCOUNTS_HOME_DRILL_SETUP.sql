    -- every open bill past its due date, BEFORE credit on account is netted off. The card
    -- shows the net figure; the difference is credit already received from the same client.
    CREATE TABLE #OB
    (
        INV_NO       VARCHAR(15),
        CLIENTCODE   VARCHAR(10),
        INV_DT       DATETIME,
        DUE_DT       DATETIME,
        DAYS_OVERDUE INT,
        BILL_AMT     FLOAT,
        RECEIVED     FLOAT,
        PENDING      FLOAT,
        LAST_RCPT_DT DATETIME
    )

    INSERT INTO #OB (INV_NO, CLIENTCODE, INV_DT, DUE_DT, DAYS_OVERDUE, BILL_AMT, RECEIVED, PENDING, LAST_RCPT_DT)
    SELECT o.INV_NO, o.CLIENTCODE, v.INV_DT, v.DUE_DT, o.OVERDUE_DAYS,
           v.TOTALAMT, ISNULL(s.ALLOC, 0), o.PENDING, lr.DT
      FROM #OPEN o
     INNER JOIN #INV v ON v.INV_NO = o.INV_NO
      LEFT JOIN #SETTLE s ON s.INV_NO = o.INV_NO
      LEFT JOIN (SELECT INV_NO, MAX(DT) AS DT FROM #SETTLEX GROUP BY INV_NO) lr ON lr.INV_NO = o.INV_NO
     WHERE o.OVERDUE_DAYS > 0

    CREATE CLUSTERED INDEX IX_OB ON #OB (INV_NO)

    -- Table : summary
    SELECT '100'                                                   AS STATUS,
           'OVERDUE'                                               AS KIND,
           CONVERT(VARCHAR(10), @ASON, 103)                        AS ASON,
           @BRANCH_LABEL                                           AS BRANCH,
           CONVERT(DECIMAL(18,2), (SELECT ISNULL(SUM(OVERDUE), 0) FROM #CLI)) AS OVERDUE_NET,
           CONVERT(DECIMAL(18,2), (SELECT ISNULL(SUM(PENDING), 0) FROM #OB))  AS OVERDUE_GROSS,
           (SELECT COUNT(*) FROM #OB)                              AS BILLS,
           (SELECT COUNT(DISTINCT CLIENTCODE) FROM #OB)            AS CLIENTS_GROSS,
           (SELECT COUNT(*) FROM #CLI WHERE OVERDUE > 0.01)        AS CLIENTS_NET

    -- Table1 : how late, on the gross bills
    SELECT B.SORT_, B.BUCKET,
           COUNT(o.INV_NO)                                         AS BILLS,
           CONVERT(DECIMAL(18,2), ISNULL(SUM(o.PENDING), 0))       AS AMOUNT
      FROM (SELECT 1 AS SORT_, '1-30 days late'    AS BUCKET, 1   AS LO, 30     AS HI
            UNION ALL SELECT 2, '31-90 days late',   31,  90
            UNION ALL SELECT 3, '91-180 days late',  91,  180
            UNION ALL SELECT 4, '181-365 days late', 181, 365
            UNION ALL SELECT 5, 'Over a year late',  366, 999999) B
      LEFT JOIN #OB o ON o.DAYS_OVERDUE BETWEEN B.LO AND B.HI
     GROUP BY B.SORT_, B.BUCKET
     ORDER BY B.SORT_

    -- Table2 : clients
    SELECT o.CLIENTCODE,
           MAX(ISNULL(c.CLIENTNAME, o.CLIENTCODE))                 AS CLIENTNAME,
           COUNT(*)                                                AS BILLS,
           CONVERT(DECIMAL(18,2), SUM(o.PENDING))                  AS OVERDUE_GROSS,
           CONVERT(DECIMAL(18,2), MAX(ISNULL(ua.UNADJUSTED, 0)))   AS CREDIT_ON_ACCOUNT,
           CONVERT(DECIMAL(18,2), MAX(ISNULL(c.OVERDUE, 0)))       AS OVERDUE_NET,
           CONVERT(DECIMAL(18,2), MAX(ISNULL(c.OUTSTANDING, 0)))   AS OUTSTANDING_NET,
           MAX(o.DAYS_OVERDUE)                                     AS OLDEST_DAYS,
           CONVERT(VARCHAR(10), MAX(o.LAST_RCPT_DT), 103)          AS LAST_RECEIPT
      FROM #OB o
      LEFT JOIN #CLI c    ON c.CLIENTCODE  = o.CLIENTCODE
      LEFT JOIN #UNADJ ua ON ua.CLIENTCODE = o.CLIENTCODE
     GROUP BY o.CLIENTCODE
     ORDER BY MAX(ISNULL(c.OVERDUE, 0)) DESC, SUM(o.PENDING) DESC

    -- Table3 : bills
    SELECT o.INV_NO,
           o.CLIENTCODE,
           CONVERT(VARCHAR(10), o.INV_DT, 103)                     AS INV_DATE,
           CONVERT(VARCHAR(8),  o.INV_DT, 112)                     AS INV_YMD,
           CONVERT(VARCHAR(10), o.DUE_DT, 103)                     AS DUE_DATE,
           o.DAYS_OVERDUE,
           CONVERT(DECIMAL(18,2), o.BILL_AMT)                      AS BILL_AMT,
           CONVERT(DECIMAL(18,2), o.RECEIVED)                      AS RECEIVED,
           CONVERT(DECIMAL(18,2), o.PENDING)                       AS PENDING,
           CONVERT(VARCHAR(10), o.LAST_RCPT_DT, 103)               AS LAST_RECEIPT
      FROM #OB o
     ORDER BY o.CLIENTCODE, o.DAYS_OVERDUE DESC

