ALTER PROCEDURE [dbo].[USP_ACC_EINVOICE_UPLOAD_XL_UPDATEGSTIRN]
--DECLARE
@EINV_IRN_UPDT_BY VARCHAR(4) ,
@EINV_IRN_UPDT_IP VARCHAR(20),
@FK_GUID VARCHAR(150) ,
@FILENAME VARCHAR(500) ,
@FILEPATH VARCHAR(500),
@TRANSTYPE VARCHAR(3)
--,
--@FK_JSONLOGID INT,
--@INVSTR VARCHAR(500)

--SET @USERID=1885
--SET	@FK_GUID ='fa82f3ad-56a5-48e9-a228-e82ae0ab4285'

AS

SET NOCOUNT ON
--/*
BEGIN
		UPDATE ACC_INVOICE_EINVOICE_EXCEL SET INV_NO='0'+INV_NO WHERE LEN(INV_NO)=14 AND USERID=@EINV_IRN_UPDT_BY AND VGUID=@FK_GUID
		DECLARE @INVNO VARCHAR(15)
		SET @INVNO =(SELECT TOP 1 SUBSTRING(INV_NO,10,1) FROM ACC_INVOICE_EINVOICE_EXCEL WHERE USERID=@EINV_IRN_UPDT_BY AND VGUID=@FK_GUID)
	
	IF(@TRANSTYPE='INV' AND @INVNO='7')
		BEGIN
		SELECT '101' AS [STATUS],STATUSTXT ='PLEASE SELECT INVOICE FILE CREDIT NOTE IRN FILE SELECTED'
		DELETE FROM ACC_INVOICE_EINVOICE_EXCEL WHERE USERID=@EINV_IRN_UPDT_BY AND VGUID=@FK_GUID
		 
		END
	ELSE	IF(@TRANSTYPE='CN' AND @INVNO='1')
		BEGIN
		SELECT '101' AS [STATUS],STATUSTXT='PLEASE SEELCT CREDITNOTE FILE INVOICE IRN FILE SELECTED'
		DELETE FROM ACC_INVOICE_EINVOICE_EXCEL WHERE USERID=@EINV_IRN_UPDT_BY AND VGUID=@FK_GUID
		END
	ELSE
	BEGIN
		IF EXISTS(SELECT INV_NO FROM ACC_INVOICE_EINVOICE_EXCEL WHERE USERID=@EINV_IRN_UPDT_BY AND VGUID=@FK_GUID)
		BEGIN	

			/*RECORD INSERT IN A EINVOICE UPLOAD EXCEL LOG FILE */
			Declare @EINVUPLOAD_ID int

			INSERT INTO TBL_ACC_EINVOICE_UPLOAD_XL_LOG (PK_GUID,FILE_TYPE,[FILENAME],FILEPATH,MAKERID,MAKERDT,MAKERIP)
			SELECT @FK_GUID,'EINVOICE EXCEL', @FILENAME,@FILEPATH,@EINV_IRN_UPDT_BY,GETDATE(),@EINV_IRN_UPDT_IP
	
			SET @EINVUPLOAD_ID=@@IDENTITY

			/* UPDATE UPLOADED FLAGS IN ACC_INVOICE_EINV_GSTIRN */

			UPDATE	ACC_INVOICE_EINV_GSTIRN 
			SET		ACKNO = B.ACKNO,
					ACKDATE = B.ACKDATE,
					QRCODE = B.QRCODE,
					IRNNO = B.IRNNO,
					EINV_IRN_UPDT_BY = @EINV_IRN_UPDT_BY,
					EINV_IRN_UPDT_DT = GETDATE(),
					EINV_IRN_UPDT_IP = @EINV_IRN_UPDT_IP,
					EINV_IRN_UPDT_GUID = @FK_GUID,
					FK_UPLOAD_ID = @EINVUPLOAD_ID
			FROM	ACC_INVOICE_EINV_GSTIRN INNER JOIN ACC_INVOICE_EINVOICE_EXCEL  B ON B.INV_NO=ACC_INVOICE_EINV_GSTIRN.INV_NO
			AND ACC_INVOICE_EINV_GSTIRN.TRANSTYPE=@TRANSTYPE
			/* ONLY THIS UPLOAD'S ROWS - STALE ROWS OF OTHER USERS/UPLOADS MUST NOT BE APPLIED */
			AND B.USERID=@EINV_IRN_UPDT_BY AND B.VGUID=@FK_GUID AND B.TRANSTYPE=@TRANSTYPE
			
			
			SELECT '100' AS [STATUS],STATUSTXT=@FILENAME + ' UPLOADED SUCCSSFULLY'

			SELECT	INVNO=SUBSTRING([INV_NO],2,14), 
					INVDATE=INV_DATE,
					SUPTYPE, 
					CLIENTNAME=EXPM.EXP_NAME, 
					IRNNO, 	ACKNO, ACKDATE, 
					[JSON CREATED BY]= RTRIM(CMPGEN.CMP_USERNAME) + ' [ ' + [dbo].[CONVERT_FORMATDATETIME] (GST.EINV_JSON_GEN_DT) + ']',
					[RESPONSE UPDATED BY]= RTRIM(CMPIRN.CMP_USERNAME) + ' [ ' + [dbo].[CONVERT_FORMATDATETIME] (GST.EINV_IRN_UPDT_DT) + ']'
			FROM	ACC_INVOICE_EINV_GSTIRN GST
					INNER JOIN EXP_MASTER EXPM ON EXPM.EXP_CODE= GST.CLIENTCODE
					LEFT OUTER JOIN CMP_DTLS CMPGEN ON CMPGEN.CMPID=GST.EINV_JSON_GEN_BY
					INNER JOIN CMP_DTLS CMPIRN ON CMPIRN.CMPID=GST.EINV_IRN_UPDT_BY
			WHERE   EINV_IRN_UPDT_GUID=@FK_GUID AND TRANSTYPE=@TRANSTYPE
					AND INV_NO IN (SELECT INV_NO FROM ACC_INVOICE_EINVOICE_EXCEL WHERE USERID=@EINV_IRN_UPDT_BY AND VGUID=@FK_GUID and TRANSTYPE=@TRANSTYPE)

			/*DELETE RECORD FROM ACC_INVOICE_EINVOICE_EXCEL AFTER  UPDATING IRNDTLS IN GSTIRN TABLE */

			DELETE FROM ACC_INVOICE_EINVOICE_EXCEL WHERE USERID=@EINV_IRN_UPDT_BY AND VGUID=@FK_GUID AND TRANSTYPE=@TRANSTYPE

		END
	END	
END
GO
